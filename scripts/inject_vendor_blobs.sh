#!/usr/bin/env bash
# Write the vendor libraries Android 14 cannot install into /vendor into the vendor staging directory.
#
#   scripts/inject_vendor_blobs.sh <lineage-tree> <device-dir> [--dry-run]
#
# This is the *last* route, and usually nothing is on it. tools/vendor_link_closure.py walks the
# DT_NEEDED graph of the kept Rockchip blobs and prefers Android 14's own vendor variant
# (`<name>.vendor` / `<name>.vendor_32`), which device.mk requests through
# device/rockchip/rk3399/vendor_modules_extra.mk - those land as real install rules, so they are in
# build_image.py's file filter and in vendor.img. A library is injected only when Android 14 has no
# vendor variant module for it and it is not a public library (the vendor namespace's public list,
# system/etc/linker.config.pb, covers libc/libm/libdl/liblog/libsync/libEGL/... without a copy).
#
# vendor_dest_keep.txt is generated by that closure from a real build, one line per file:
#   <vendor-relative-path>\t<source-file>\t<reason>
# The source is absolute (Android 14's own copy under out/target/product/.../<partition>/) or relative
# to the device dir (prebuilt_vendor_libs/, extracted from a reference firmware partition).
#
# Files written here are *not* install deps, so Make's filter file excludes them and the product
# vendor.img would omit them; scripts/package.sh's sync_vendor_image() takes dist's IMAGES/vendor.img
# (built from the whole VENDOR/ directory) in that case.
set -eu
TREE=${1:?usage: inject_vendor_blobs.sh <lineage-tree> <device-dir> [--dry-run]}
DEV=${2:?no device dir}
DRY=${3:-}
KEEP=$DEV/vendor_dest_keep.txt
STAGE=$TREE/out/target/product/rk3399/vendor

if [ ! -s "$KEEP" ]; then
  echo "  nothing to inject (no $KEEP): every library the blobs link is a vendor variant or a public library"
  exit 0
fi
[ -d "$STAGE" ] || { echo "  ! vendor staging dir does not exist yet: $STAGE"; exit 1; }

copied=0 skipped=0
while IFS=$'\t' read -r rel src reason; do
  case "$rel" in ''|'#'*) continue ;; esac
  # A module may already have installed the same path (a vendor variant we now request). Do not put a
  # second provenance on the same file.
  if [ -e "$STAGE/$rel" ]; then
    skipped=$((skipped + 1))
    continue
  fi
  case "$src" in
    /*) srcpath="$src" ;;
    *)  srcpath="$DEV/$src"; [ -f "$srcpath" ] || srcpath="$TREE/$src" ;;
  esac
  if [ ! -f "$srcpath" ]; then
    echo "  ! listed in vendor_dest_keep.txt but no source file: $rel ($src)"
    exit 1
  fi
  mkdir -p "$STAGE/$(dirname "$rel")"
  if [ "$DRY" != "--dry-run" ]; then
    cp -a "$srcpath" "$STAGE/$rel"
    echo "  injected $rel <- $srcpath ($reason)"
  fi
  copied=$((copied + 1))
done < "$KEEP"

echo "  injected $copied library(ies) into $STAGE (skipped $skipped already installed by a module)"
if [ "$DRY" = "--dry-run" ]; then exit 0; fi

# ninja only rebuilds an image whose declared inputs change; injected files are not inputs, so delete
# the built image and the copy inside target_files to force a fresh one.
PROD=$TREE/out/target/product/rk3399
STAGES=$(ls -d "$PROD"/obj/PACKAGING/target_files_intermediates/*/IMAGES 2>/dev/null | head -1)
for f in "$PROD/vendor.img" "$STAGES/vendor.img"; do
  [ -n "$f" ] && [ -f "$f" ] && { rm -f "$f"; echo "  removed stale $f (rebuilds from the staging dir)"; }
done
