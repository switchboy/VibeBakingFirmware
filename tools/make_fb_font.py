#!/usr/bin/env python3
"""Rasterise a monospace TTF into the C header the panel painter reads: fbtext/fb_font.h.

  python3 tools/make_fb_font.py                 # writes device/rk3399-px6-hct4/fbtext/fb_font.h
  python3 tools/make_fb_font.py --cell 10x16 --size 13 --font <path>

Deterministic: the same font file and cell always produce byte-identical output, so the header's
sha256 can be recorded in docs/flash.md and compared across builds.

Cell bit order: bit 0 (LSB) = leftmost pixel of that row, MSB = rightmost. hu_fblog.c relies on
that, plus FB_FONT_W / FB_FONT_H / FB_FONT_FIRST / FB_FONT_LAST.
"""
import hashlib
import os
import subprocess
import sys
from PIL import Image, ImageDraw, ImageFont

REPO = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
OUT = os.path.join(REPO, "device", "rk3399-px6-hct4", "fbtext", "fb_font.h")
FIRST, LAST = 0x20, 0x7E

args = sys.argv[1:]
cell = "10x16"
size = 13
font_path = None
for a in args:
    if a.startswith("--cell="):
        cell = a.split("=", 1)[1]
    elif a.startswith("--size="):
        size = int(a.split("=", 1)[1])
    elif a.startswith("--font="):
        font_path = a.split("=", 1)[1]
W, H = (int(x) for x in cell.split("x"))


def pick_font():
    if font_path:
        return font_path
    try:
        listing = subprocess.run(["fc-list"], capture_output=True, text=True, timeout=20).stdout
    except Exception:
        listing = ""
    lines = [l.split(":")[0].strip() for l in listing.splitlines() if l.strip()]
    mono = [l for l in lines if "Mono" in l or "mono" in l]
    for pref in ("DejaVuSansMono.ttf", "NotoSansMono-Regular.ttf", "NotoSansMono.ttf"):
        for l in mono:
            if l.endswith(pref):
                return l
    # Avoid weight variants: Bold/Light/Thin/Black rasterise to different metrics.
    plain = [l for l in mono if not any(w in l for w in ("Bold", "Light", "Thin", "Black", "Italic"))]
    if plain:
        return sorted(plain)[0]
    if mono:
        return sorted(mono)[0]
    for l in lines:
        if l.endswith(".ttf"):
            return l
    raise SystemExit("no TTF found via fc-list; pass --font=<path>")


def glyph(font, ch):
    """Rasterise one glyph into a W x H bitmap, with the baseline at row H-3 of the cell."""
    asc, desc = font.getmetrics()
    canvas = Image.new("1", (W * 4, H * 2), 0)
    d = ImageDraw.Draw(canvas)
    # Default anchor is top-left at the ascender line: drawing at y=H puts the baseline at H+asc.
    d.text((W * 2, H), ch, font=font, fill=1)
    box = canvas.getbbox()
    if box is None:
        return [0] * H
    g = canvas.crop(box)
    baseline = (H + asc) - box[1]          # rows from the glyph box top down to the baseline
    # Scale down only when the glyph is wider than the cell; never upscale, or spacing drifts.
    if g.width > W:
        orig_h = g.height
        nh = max(1, int(orig_h * W / g.width))
        g = g.resize((W, nh))
        baseline = int(baseline * nh / orig_h) if orig_h else baseline
    top = (H - 3) - baseline               # keep the baseline 3 px above the cell bottom
    out = [0] * H
    px = g.load()
    for y in range(g.height):
        row = top + y
        if row < 0 or row >= H:
            continue
        bits = 0
        for x in range(min(g.width, W)):
            if px[x, y]:
                bits |= 1 << x          # bit 0 = leftmost pixel
        out[row] |= bits
    return out


def main():
    path = pick_font()
    font = ImageFont.truetype(path, size)
    glyphs = {ord(c): glyph(font, c) for c in map(chr, range(FIRST, LAST + 1))}

    lines = [
        "/* Generated by tools/make_fb_font.py - do not edit by hand.",
        " * Font: %s rasterised at %d px into a %dx%d cell, ASCII 0x20..0x7E." % (path, size, W, H),
        " * Row bits: bit 0 = leftmost pixel. hu_fblog.c reads FB_FONT_W/H/FIRST/LAST.",
        " */",
        "#ifndef HU_FB_FONT_H",
        "#define HU_FB_FONT_H",
        "#define FB_FONT_W %d" % W,
        "#define FB_FONT_H %d" % H,
        "#define FB_FONT_FIRST %d" % FIRST,
        "#define FB_FONT_LAST  %d" % LAST,
        "static const unsigned short fb_font[%d][FB_FONT_H] = {" % (LAST - FIRST + 1),
    ]
    for code in range(FIRST, LAST + 1):
        rows = glyphs[code]
        lines.append("  /* %3d %s */ { %s }," % (
            code, (chr(code) if code != 0x20 else "space"),
            ", ".join(str(r) for r in rows)))
    lines.append("};")
    lines.append("#endif")
    body = "\n".join(lines) + "\n"

    os.makedirs(os.path.dirname(OUT), exist_ok=True)
    tmp = OUT + ".tmp"
    with open(tmp, "w") as f:
        f.write(body)
        f.flush()
        os.fsync(f.fileno())
    os.replace(tmp, OUT)

    sha = hashlib.sha256(body.encode()).hexdigest()
    print("wrote %s (%d bytes, %d glyphs, cell %dx%d)" % (OUT, len(body), LAST - FIRST + 1, W, H))
    print("sha256 %s" % sha)

    # Preview so a human can eyeball legibility without booting anything.
    for ch in "Ab9 ."[:5]:
        rows = glyphs[ord(ch)]
        print("--- %r" % ch)
        for r in rows:
            print("".join("#" if (r >> x) & 1 else "." for x in range(W)))


if __name__ == "__main__":
    main()
