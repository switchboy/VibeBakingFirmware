#!/usr/bin/env python3
"""Generate the vendor staging config for the PX6 HU from the extracted Android 11 vendor tree.

  tools/gen_vendor_staging.py <vendor-tree-dir> <device-dir> [--src-prefix vendor/hct4/tree/vendor]

Android 14's OTA packer only works when the vendor image is *built* (it needs a VENDOR/ staging
directory, vendor.map and a vendor build.prop), so the stock blobs are staged through the build
instead of being used as BOARD_PREBUILT_VENDORIMAGE. This script turns the extracted tree into:

  <device-dir>/vendor_staging.mk   PRODUCT_COPY_FILES entries for every blob, plus the VINTF
                                   vendor manifest via DEVICE_MANIFEST_FILE (PRODUCT_COPY_FILES
                                   into vendor/etc/vintf/ is a hard build error -
                                   build/make/core/Makefile:131)
  <device-dir>/vendor_props.mk     the stock vendor build.prop properties, re-declared as
                                   PRODUCT_PROPERTY_OVERRIDES so the HALs keep reading the same
                                   ro.* values (generated build.prop only carries our own props)

The stock vendor compatibility matrix is deliberately dropped: it declares
<vendor-ndk><version>30</version>, and Android 14 has no VNDK, so `checkvintf --check-compat`
reports "Framework manifest and device compatibility matrix are incompatible: Vndk version 30 is
not supported". Instead we ship vintf/device_framework_matrix.xml (DEVICE_FRAMEWORK_COMPATIBILITY_MATRIX_FILE)
for the three HALs the Android 14 framework matrices do not know about - android.hardware.mtc.mfi,
rockchip.hardware.outputmanager and rockchip.hardware.rockit.hw.

Deliberately not copied: build.prop / default.prop (generated by the build), recovery-from-boot.p
(Android 11 recovery payload), the /vendor/odm symlink, lost+found, our own overlay files (they are
copied from device/rk3399-px6-hct4 by device.mk), and symlinks. `scripts/prebuilt_vendor.sh`
materialises the GPU alias symlinks as real copies, because cp/ACP dereferences symlinks and the
187 vendor/bin toybox aliases would each become a full toybox copy (~280 MB).
"""
import argparse
import os
import re

SKIP_DEST = {
    "build.prop",
    "default.prop",
    "recovery-from-boot.p",
    "odm",
    "lost+found",
    # our own overlays, copied by device.mk from the device directory
    "etc/fstab.rk30board",
    "etc/ueventd.rc",
    "etc/init/hu.rc",
    "etc/hu_insmod.sh",
    # VINTF metadata goes through DEVICE_MANIFEST_FILE / DEVICE_MATRIX_FILE
    "etc/vintf/manifest.xml",
    "etc/vintf/compatibility_matrix.xml",
    "manifest.xml",
    "compatibility_matrix.xml",
}

# Properties Android 14's build assigns itself in vendor/build.prop, or that device.mk already
# assigns - declaring either again makes post_process_props.py abort on duplicate sysprops.
PROP_SKIP_PREFIXES = ("ro.build.", "ro.vendor.build.", "ro.system.build.", "ro.product.",
                      "ro.bootimage.", "ro.boot.", "ro.system.", "ro.debuggable",
                      "ro.wifi.channels", "ro.url.legal", "rild.libpath", "rild.libprefix")
# Everything else in the stock build.prop is kept: the Rockchip HALs read wifi.interface,
# ro.vendor.mpp_buf_type, ro.rk.* etc., and dropping one silently breaks that HAL.
PROP_SKIP_KEYS = {"ro.hwui.use_vulkan",          # from TARGET_USES_VULKAN (main.mk:337)
                  "ro.sf.lcd_density",           # from TARGET_SCREEN_DENSITY
                  "ro.vendor.build.security_patch",
                  "ro.product.first_api_level",
                  "ro.hardware.egl", "ro.opengles.version",           # set in device.mk
                  "dalvik.vm.heapsize", "dalvik.vm.heapgrowthlimit"}  # set in device.mk
PROP_PROP_RE = re.compile(r"^([A-Za-z0-9_.]+)=(.*)$")


def walk_files(root):
    out = []
    for dirpath, dirnames, filenames in os.walk(root):
        dirnames[:] = [d for d in dirnames if d != "lost+found"]
        for name in filenames:
            path = os.path.join(dirpath, name)
            if name.endswith(".link"):
                continue
            if os.path.islink(path):
                continue
            if os.path.getsize(path) == 0 and name.endswith(".so"):
                continue
            out.append(os.path.relpath(path, root))
    return sorted(out)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("tree", help="extracted vendor directory (the partition root)")
    ap.add_argument("device_dir", help="where the generated .mk files are written")
    ap.add_argument("--src-prefix", default="vendor/hct4/tree/vendor",
                    help="the tree's path as the build sees it (relative to the AOSP root)")
    ap.add_argument("--build-prop", default=None,
                    help="stock vendor build.prop; the staged tree excludes it (Android 14 "
                         "generates its own), so scripts/prebuilt_vendor.sh keeps a copy in "
                         "vendor/hct4/prebuilt/. Defaults to <tree>/build.prop if present.")
    ap.add_argument("--skip-file", help="extra property keys to drop, one per line")
    ap.add_argument("--compat-matrix", default=None,
                    help="stock vendor compatibility matrix; scripts/prebuilt_vendor.sh keeps a "
                         "copy in vendor/hct4/prebuilt/ because the staged tree excludes it")
    args = ap.parse_args()

    tree = os.path.abspath(args.tree)
    if not os.path.isdir(os.path.join(tree, "etc")):
        raise SystemExit("%s does not look like a vendor partition root (no etc/)" % tree)

    extra_skip = PROP_SKIP_KEYS
    if args.skip_file and os.path.exists(args.skip_file):
        extra_skip |= {l.strip() for l in open(args.skip_file) if l.strip() and not l.startswith("#")}

    entries = []
    manifest = None
    for rel in walk_files(tree):
        if rel in SKIP_DEST:
            continue
        dest = "$(TARGET_COPY_OUT_VENDOR)/" + rel
        entries.append("%s/%s:%s" % (args.src_prefix.rstrip("/"), rel, dest))
    if os.path.exists(os.path.join(tree, "etc/vintf/manifest.xml")):
        manifest = "%s/etc/vintf/manifest.xml" % args.src_prefix.rstrip("/")

    staging = os.path.join(args.device_dir, "vendor_staging.mk")
    with open(staging, "w") as f:
        f.write("# GENERATED by tools/gen_vendor_staging.py from the extracted Android 11 vendor\n"
                "# tree (scripts/prebuilt_vendor.sh). Do not edit by hand; regenerate.\n"
                "# The blobs themselves are byte-identical to the stock vendor image\n"
                "# (tools/vendor_diff.py checks the prebuilt reference).\n\n")
        f.write("PRODUCT_COPY_FILES += \\\n")
        f.write("    " + " \\\n    ".join(entries) + "\n")
        if manifest:
            f.write("\n# The stock vendor HAL manifest (target-level 5, HIDL + the power AIDL fragment).\n"
                    "# vendor/etc/vintf/ is VINTF metadata, which PRODUCT_COPY_FILES rejects\n"
                    "# (build/make/core/Makefile:131), so it goes in here.\n"
                    "DEVICE_MANIFEST_FILE += %s\n" % manifest)

    # Stock device compatibility matrix, with <vendor-ndk> removed. Android 14 has no VNDK, so a
    # matrix that declares <vendor-ndk><version>30</version> makes checkvintf report "Vndk version
    # 30 is not supported" and the build aborts. Everything else is kept: the entries name the
    # framework services the Rockchip HALs talk to (hwservicemanager, hidl allocator/token), and
    # Android 14's framework manifest still provides those (system_ext/etc/vintf/manifest/).
    # It is rewritten into the device folder, because DEVICE_MATRIX_FILE installs it as
    # /vendor/etc/vintf/compatibility_matrix.xml and feeds it to the build-time check too.
    matrix_src = args.compat_matrix or os.path.join(tree, "etc/vintf/compatibility_matrix.xml")
    if os.path.exists(matrix_src):
        text = open(matrix_src, encoding="utf-8", errors="replace").read()
        text = re.sub(r"\n?\s*<vendor-ndk>.*?</vendor-ndk>\n?", "\n", text, flags=re.S)
        os.makedirs(os.path.join(args.device_dir, "vintf"), exist_ok=True)
        mpath = os.path.join(args.device_dir, "vintf", "device_matrix.xml")
        with open(mpath, "w") as f:
            f.write("<!-- GENERATED by tools/gen_vendor_staging.py from the stock Android 11 vendor\n"
                    "     compatibility matrix, with the <vendor-ndk> block removed (Android 14 has\n"
                    "     no VNDK). Regenerated by scripts/prebuilt_vendor.sh; do not edit. -->\n")
            f.write(text)
        with open(staging, "a") as f:
            f.write("\n# The stock device compatibility matrix minus the vendor-ndk declaration.\n"
                    "# DEVICE_MATRIX_FILE installs it at /vendor/etc/vintf/compatibility_matrix.xml.\n"
                    "DEVICE_MATRIX_FILE += device/rockchip/rk3399/vintf/device_matrix.xml\n")
        print("wrote %s (vendor-ndk removed)" % mpath)
    print("wrote %s (%d copy entries, manifest=%s)" % (staging, len(entries), bool(manifest)))

    # Stock vendor properties -> PRODUCT_PROPERTY_OVERRIDES.
    props = []
    bp = args.build_prop or os.path.join(tree, "build.prop")
    if not os.path.exists(bp):
        print("  ! no stock vendor build.prop found at %s - vendor_props.mk will be empty" % bp)
    else:
        for line in open(bp, encoding="utf-8", errors="replace"):
            m = PROP_PROP_RE.match(line.strip())
            if not m:
                continue
            key, value = m.group(1), m.group(2)
            if key.startswith(PROP_SKIP_PREFIXES) or key in extra_skip or not value:
                continue
            if any(c in value for c in "&;$`\\"):
                continue
            props.append("%s=%s" % (key, value))
    props = sorted(set(props))
    out = os.path.join(args.device_dir, "vendor_props.mk")
    with open(out, "w") as f:
        f.write("# GENERATED by tools/gen_vendor_staging.py from the stock vendor build.prop.\n"
                "# Android 14 generates its own vendor build.prop, so the properties the Rockchip\n"
                "# HALs and the HCT apps read have to be declared here instead.\n"
                "# Keys the build assigns itself (or that collide) are dropped; if post_process_props\n"
                "# reports a duplicate, add it to vendor_props_skip.txt and regenerate.\n")
        if props:
            f.write("\nPRODUCT_PROPERTY_OVERRIDES += \\\n")
            f.write("    " + " \\\n    ".join(props) + "\n")
    print("wrote %s (%d properties)" % (out, len(props)))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
