#!/usr/bin/env python3
"""Generate the vendor staging config for the PX6 HU from the extracted Android 11 vendor tree.

  tools/gen_vendor_staging.py <vendor-tree-dir> <device-dir> [--src-prefix vendor/hct4/tree/vendor]

Android 14's OTA packer only works when the vendor image is *built* (it needs a VENDOR/ staging
directory, vendor.map and a vendor build.prop), so the stock blobs are staged through the build
instead of being used as BOARD_PREBUILT_VENDORIMAGE. This script turns the extracted tree into:

  <device-dir>/vendor_staging.mk   PRODUCT_COPY_FILES entries for every blob, plus the VINTF
                                   vendor manifest via DEVICE_MANIFEST_FILE (PRODUCT_COPY_FILES
                                   into vendor/etc/vintf/ is a hard build error -
                                   build/make/core/Makefile:131). The manifest is a rewritten
                                   copy in vintf/vendor_manifest.xml: its Android 11 <sepolicy>
                                   version is dropped (assemble_vintf refuses to override a value
                                   the file already declares with Android 14's
                                   BOARD_SEPOLICY_VERS=202404), and so are HAL blocks that a
                                   build-installed manifest fragment already declares
                                   (vintf/manifest_fragments.txt), because the fragment is merged
                                   into the same manifest and a duplicate FqInstance is fatal
  <device-dir>/vendor_props.mk     the stock vendor build.prop properties, re-declared as
                                   PRODUCT_PROPERTY_OVERRIDES so the HALs keep reading the same
                                   ro.* values (generated build.prop only carries our own props)
  <device-dir>/prebuilt_apps/Android.mk  BUILD_PREBUILT modules for anything PRODUCT_COPY_FILES
                                   refuses by destination type: .apk is rejected outright
                                   ("Prebuilt apk found in PRODUCT_COPY_FILES", Makefile:118), so
                                   the stock vendor resource-overlay package is installed by a
                                   module instead (see docs/build-host.md)

The stock vendor compatibility matrix is deliberately dropped: it declares
<vendor-ndk><version>30</version>, and Android 14 has no VNDK, so `checkvintf --check-compat`
reports "Framework manifest and device compatibility matrix are incompatible: Vndk version 30 is
not supported". Instead we ship vintf/device_framework_matrix.xml (DEVICE_FRAMEWORK_COMPATIBILITY_MATRIX_FILE)
for the three HALs the Android 14 framework matrices do not know about - android.hardware.mtc.mfi,
rockchip.hardware.outputmanager and rockchip.hardware.rockit.hw.

Deliberately not copied: build.prop / default.prop (generated by the build), recovery-from-boot.p
(Android 11 recovery payload), the /vendor/odm symlink, lost+found, our own overlay files (they are
copied from device/rk3399-px6-hct4 by device.mk), and symlinks. `scripts/prebuilt_vendor.sh`
materialises the GPU alias symlinks as real copies, because cp/ACP dereferences symlinks and the
178 vendor/bin toybox aliases (plus the libOpenCL.so.1/.1.1 chain) would each become a full
toybox_vendor copy (~280 MB).
"""
import argparse
import os
import re

SKIP_DEST = {
    "build.prop",
    "default.prop",
    "recovery-from-boot.p",
    "odm",
    "lost+found",
    # our own overlays, copied by device.mk from the device directory
    "etc/fstab.rk30board",
    "etc/ueventd.rc",
    "etc/init/hu.rc",
    "etc/hu_insmod.sh",
    # VINTF metadata goes through DEVICE_MANIFEST_FILE / DEVICE_MATRIX_FILE
    "etc/vintf/manifest.xml",
    "etc/vintf/compatibility_matrix.xml",
    "manifest.xml",
    "compatibility_matrix.xml",
}

# Properties Android 14's build assigns itself in vendor/build.prop, or that device.mk already
# assigns - declaring either again makes post_process_props.py abort on duplicate sysprops.
PROP_SKIP_PREFIXES = ("ro.build.", "ro.vendor.build.", "ro.system.build.", "ro.product.",
                      "ro.bootimage.", "ro.boot.", "ro.system.", "ro.debuggable",
                      "ro.wifi.channels", "ro.url.legal", "rild.libpath", "rild.libprefix")
# Everything else in the stock build.prop is kept: the Rockchip HALs read wifi.interface,
# ro.vendor.mpp_buf_type, ro.rk.* etc., and dropping one silently breaks that HAL.
PROP_SKIP_KEYS = {"ro.hwui.use_vulkan",          # from TARGET_USES_VULKAN (main.mk:337)
                  "ro.sf.lcd_density",           # from TARGET_SCREEN_DENSITY
                  "ro.vendor.build.security_patch",
                  "ro.product.first_api_level",
                  "ro.hardware.egl", "ro.opengles.version",           # set in device.mk
                  "dalvik.vm.heapsize", "dalvik.vm.heapgrowthlimit"}  # set in device.mk
PROP_PROP_RE = re.compile(r"^([A-Za-z0-9_.]+)=(.*)$")


def walk_files(root):
    out = []
    for dirpath, dirnames, filenames in os.walk(root):
        dirnames[:] = [d for d in dirnames if d != "lost+found"]
        for name in filenames:
            path = os.path.join(dirpath, name)
            if name.endswith(".link"):
                continue
            if os.path.islink(path):
                continue
            if os.path.getsize(path) == 0 and name.endswith(".so"):
                continue
            out.append(os.path.relpath(path, root))
    return sorted(out)


def fragment_declarations(path):
    """`<hal-name>@<version>::<fqname>` lines that Android 14's modules install as manifest
    fragments; see vintf/manifest_fragments.txt. assemble_vintf merges that directory into
    /vendor/etc/vintf/manifest.xml and fails on a duplicate FqInstance."""
    if not os.path.isfile(path):
        return set()
    return {line.split("#", 1)[0].strip() for line in open(path, errors="replace")
            if line.strip() and not line.strip().startswith("#")}


def strip_fragment_hals(text, decls):
    """Remove <hal> blocks whose declaration a manifest fragment already carries."""
    removed = []

    def repl(m):
        block = m.group(0)
        name = re.search(r"<name>(.*?)</name>", block, flags=re.S)
        ver = re.search(r"<version>(.*?)</version>", block, flags=re.S)
        fq = re.search(r"<fqname>(.*?)</fqname>", block, flags=re.S)
        if not (name and fq):
            return block
        # A manifest's <fqname> is already version-prefixed: "@2.1::IHealth/default". The canonical
        # declaration is `<name>@<version>::<interface>`, so the version comes out of the fqname and
        # only the interface part is kept - otherwise the key says health@2.1::@2.1::IHealth/default
        # and never matches vintf/manifest_fragments.txt.
        fq_txt = fq.group(1).strip()
        iface, vfromfq = fq_txt, ""
        if fq_txt.startswith("@") and "::" in fq_txt:
            vfromfq, iface = fq_txt[1:].split("::", 1)
        version = (ver.group(1).strip() if ver else "") or vfromfq
        decl = "%s@%s::%s" % (name.group(1).strip(), version, iface)
        if decl in decls:
            removed.append(decl)
            return ""
        return block

    return re.sub(r"\s*<hal\b[^>]*>.*?</hal>", repl, text, flags=re.S), removed


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("tree", help="extracted vendor directory (the partition root)")
    ap.add_argument("device_dir", help="where the generated .mk files are written")
    ap.add_argument("--src-prefix", default="vendor/hct4/tree/vendor",
                    help="the tree's path as the build sees it (relative to the AOSP root)")
    ap.add_argument("--build-prop", default=None,
                    help="stock vendor build.prop; the staged tree excludes it (Android 14 "
                         "generates its own), so scripts/prebuilt_vendor.sh keeps a copy in "
                         "vendor/hct4/prebuilt/. Defaults to <tree>/build.prop if present.")
    ap.add_argument("--skip-file", help="extra property keys to drop, one per line")
    ap.add_argument("--dest-skip",
                    help="destination paths (partition-relative) to leave out of the copy list, "
                         "because the build installs that path itself - written by "
                         "tools/vendor_conflicts.py --write-drop-list")
    ap.add_argument("--compat-matrix", default=None,
                    help="stock vendor compatibility matrix; scripts/prebuilt_vendor.sh keeps a "
                         "copy in vendor/hct4/prebuilt/ because the staged tree excludes it")
    ap.add_argument("--reference-label", default="Android 11",
                    help="which firmware the staged tree came from; only used in the generated "
                         "file headers, so an Android 10 restage says so instead of 'Android 11'")
    args = ap.parse_args()

    tree = os.path.abspath(args.tree)
    if not os.path.isdir(os.path.join(tree, "etc")):
        raise SystemExit("%s does not look like a vendor partition root (no etc/)" % tree)

    label = args.reference_label

    extra_skip = PROP_SKIP_KEYS
    if args.skip_file and os.path.exists(args.skip_file):
        # One key per line; a '#' starts a comment, so inline notes are allowed.
        extra_skip |= {line.split("#", 1)[0].strip()
                       for line in open(args.skip_file)
                       if line.strip() and not line.strip().startswith("#")}

    # Destinations the build installs itself. PRODUCT_COPY_FILES would create a second rule for
    # the same target and ckati aborts ("overriding commands for target ... previously defined at
    # out/soong/installs-<product>.mk"); these paths get Android 14's own build of the component.
    dest_skip = set()
    if args.dest_skip and os.path.exists(args.dest_skip):
        dest_skip = {line.split("#", 1)[0].strip()
                     for line in open(args.dest_skip)
                     if line.strip() and not line.strip().startswith("#")}

    entries = []
    odd_names = []
    apks = []
    build_dropped = []
    for rel in walk_files(tree):
        if rel in SKIP_DEST:
            continue
        if rel in dest_skip:
            build_dropped.append(rel)
            continue
        # PRODUCT_COPY_FILES rejects any destination ending in .apk
        # ("Prebuilt apk found in PRODUCT_COPY_FILES: ..., use BUILD_PREBUILT instead!",
        # build/make/core/Makefile:118). This partition has exactly one: the auto-generated
        # vendor resource-overlay package (framework-res__auto_generated_rro_vendor.apk), which
        # overrides config_autoBrightness*, config_tether_{usb,bluetooth,wifi}_regexs,
        # config_networkSupportedKeepaliveCount, config_ephemeralResolverPackage and the
        # config_enable* bools - i.e. the HU's auto-brightness curve and its tether/hotspot
        # interface names. Dropping it would change that behaviour, so it is staged as a
        # BUILD_PREBUILT module (see prebuilt_apps/Android.mk below) instead.
        if rel.endswith(".apk"):
            apks.append(rel)
            continue
        # Make cannot carry these characters in a src:dst pair, and each breaks the build in a
        # different way: '#' starts a comment (the entry is truncated -> "malformed COPY_FILE"),
        # ':' is the pair separator itself, whitespace splits the word, '=' makes the generated
        # `$(dst): $(src)` line an assignment ("commands commence before first target",
        # build/make/core/Makefile:161), and % * ? [ ] are wildcard characters that turn the rule
        # into a pattern rule. The rest are shell/Make-function meaningful in the recipe.
        # tools/namecheck.py <tree> lists whatever is present. On this vendor partition the hits
        # are all usb_modeswitch.d rules: three named with '#' (12d1_#android, 12d1_#linux,
        # 19d2_#linux) and twenty named with '=' (uMa=/sMo=/sVe= variant rules). The HU's own
        # /vendor/bin/usb_dongle only looks up "/vendor/etc/usb_modeswitch.d/%04x_%04x", so none of
        # them are used, and the plain <vendor>_<product> rules are still staged.
        if any(c in rel for c in "#:= \t\n%*?[]{}()<>|;&'\"`$\\"):
            odd_names.append(rel)
            continue
        dest = "$(TARGET_COPY_OUT_VENDOR)/" + rel
        entries.append("%s/%s:%s" % (args.src_prefix.rstrip("/"), rel, dest))
    if odd_names:
        print("  skipped %d file(s) Make cannot express (one per line):" % len(odd_names))
        for rel in odd_names[:20]:
            print("    %s" % rel)
    if build_dropped:
        print("  dropped %d destination(s) the build installs itself (see vendor_conflicts.py);" %
              len(build_dropped))
        for rel in sorted(build_dropped)[:12]:
            print("    %s" % rel)
        if len(build_dropped) > 12:
            print("    ... and %d more" % (len(build_dropped) - 12))
    # The stock vendor manifest, rewritten into the device folder. Two reasons it cannot be used
    # as-is:
    #  - vendor/etc/vintf/ is VINTF metadata, which PRODUCT_COPY_FILES rejects
    #    (build/make/core/Makefile:131), so it goes in via DEVICE_MANIFEST_FILE.
    #  - it declares <sepolicy><version>...</version> (Android 11: 30.0, Android 10: 29.0).
    #    assemble_vintf only fills a value in when the file has none; an existing value that
    #    differs from the build's is fatal, and Android 14 sets BOARD_SEPOLICY_VERS=202404, so the
    #    pass stopped with "Cannot override existing value 30.0 with BOARD_SEPOLICY_VERS (which is
    #    202404)". The block is dropped and assemble_vintf writes 202404 - correct, because the
    #    vendor sepolicy in this ROM is Android 14's, built by the build from AOSP/Lineage policy.
    #    Everything else is kept verbatim, including target-level. Android 14 ships both
    #    compatibility_matrix.4.xml and .5.xml, so an Android 10-era manifest (level 4, measured
    #    Nov 15: 61 entries, all optional=true, zero mandatory, no <kernel>) and an Android 11-era
    #    one (level 5) are both accepted, and raising or lowering either would change which HIDL
    #    HALs the HU depends on. No <kernel> tag is ever added: libvintf only checks kernel
    #    compatibility when the manifest declares one (HalManifest.cpp:576, used at 554).
    manifest = None
    manifest_src = os.path.join(tree, "etc/vintf/manifest.xml")
    if os.path.exists(manifest_src):
        text = open(manifest_src, encoding="utf-8", errors="replace").read()
        text = re.sub(r"\n?\s*<sepolicy>.*?</sepolicy>\n?", "\n", text, flags=re.S)
        # Duplicate HAL declarations are fatal: Android 14's service modules install their own
        # fragment in /vendor/etc/vintf/manifest/, and assemble_vintf merges that directory into the
        # manifest, so a stock entry for the same interface aborts `m dist` with "Conflicting
        # FqInstance". The fragment carries the declaration instead - same merged result on device.
        frag_file = os.path.join(args.device_dir, "vintf", "manifest_fragments.txt")
        text, removed = strip_fragment_hals(text, fragment_declarations(frag_file))
        if removed:
            print("dropped %d HAL block(s) already declared by a build-installed fragment: %s"
                  % (len(removed), ", ".join(sorted(removed))))
        os.makedirs(os.path.join(args.device_dir, "vintf"), exist_ok=True)
        vpath = os.path.join(args.device_dir, "vintf", "vendor_manifest.xml")
        level = re.search(r'target-level="(\d+)"', text)
        with open(vpath, "w") as f:
            f.write("<!-- GENERATED by tools/gen_vendor_staging.py from the stock %s vendor\n" % label)
            f.write("     manifest, with the <sepolicy> block removed (Android 14 sets\n"
                    "     BOARD_SEPOLICY_VERS=202404 and assemble_vintf refuses to override a value\n"
                    "     the file already declares). HAL entries and target-level=%s are untouched,\n"
                    % (level.group(1) if level else "unknown")
                    + "     and no <kernel> tag is added (libvintf checks kernel compatibility only if\n"
                      "     the manifest declares one). Regenerated by scripts/prebuilt_vendor.sh;\n"
                      "     do not edit. -->\n")
            f.write(text)
        print("wrote %s (sepolicy version removed, target-level=%s)"
              % (vpath, level.group(1) if level else "unknown"))
        manifest = "device/rockchip/rk3399/vintf/vendor_manifest.xml"

    staging = os.path.join(args.device_dir, "vendor_staging.mk")
    with open(staging, "w") as f:
        f.write("# GENERATED by tools/gen_vendor_staging.py from the extracted %s vendor\n" % label)
        f.write("# tree (scripts/prebuilt_vendor.sh). Do not edit by hand; regenerate.\n"
                "# The blobs themselves are byte-identical to the stock vendor image\n"
                "# (tools/vendor_diff.py checks the prebuilt reference).\n\n")
        f.write("PRODUCT_COPY_FILES += \\\n")
        f.write("    " + " \\\n    ".join(entries) + "\n")
        if manifest:
            f.write("\n# The stock vendor HAL manifest (target-level %s, HIDL plus any AIDL\n"
                    % (level.group(1) if level else "unknown"))
            f.write("# fragment), with its stock <sepolicy> version dropped so Android 14's\n"
                    "# BOARD_SEPOLICY_VERS=202404 is applied instead. vendor/etc/vintf/ is VINTF\n"
                    "# metadata, which PRODUCT_COPY_FILES rejects (build/make/core/Makefile:131),\n"
                    "# so it goes in here.\n"
                    "DEVICE_MANIFEST_FILE += %s\n" % manifest)

    # Stock device compatibility matrix, with <vendor-ndk> removed. Android 14 has no VNDK, so a
    # matrix that declares <vendor-ndk><version>30</version> makes checkvintf report "Vndk version
    # 30 is not supported" and the build aborts. Everything else is kept: the entries name the
    # framework services the Rockchip HALs talk to (hwservicemanager, hidl allocator/token), and
    # Android 14's framework manifest still provides those (system_ext/etc/vintf/manifest/).
    # It is rewritten into the device folder, because DEVICE_MATRIX_FILE installs it as
    # /vendor/etc/vintf/compatibility_matrix.xml and feeds it to the build-time check too.
    matrix_src = args.compat_matrix or os.path.join(tree, "etc/vintf/compatibility_matrix.xml")
    if os.path.exists(matrix_src):
        text = open(matrix_src, encoding="utf-8", errors="replace").read()
        text = re.sub(r"\n?\s*<vendor-ndk>.*?</vendor-ndk>\n?", "\n", text, flags=re.S)
        os.makedirs(os.path.join(args.device_dir, "vintf"), exist_ok=True)
        mpath = os.path.join(args.device_dir, "vintf", "device_matrix.xml")
        with open(mpath, "w") as f:
            f.write("<!-- GENERATED by tools/gen_vendor_staging.py from the stock %s vendor\n" % label)
            f.write("     compatibility matrix, with the <vendor-ndk> block removed (Android 14 has\n"
                    "     no VNDK). Regenerated by scripts/prebuilt_vendor.sh; do not edit. -->\n")
            f.write(text)
        with open(staging, "a") as f:
            f.write("\n# The stock device compatibility matrix minus the vendor-ndk declaration.\n"
                    "# DEVICE_MATRIX_FILE installs it at /vendor/etc/vintf/compatibility_matrix.xml.\n"
                    "DEVICE_MATRIX_FILE += device/rockchip/rk3399/vintf/device_matrix.xml\n")
        print("wrote %s (vendor-ndk removed)" % mpath)

    # Vendor APKs are not allowed in PRODUCT_COPY_FILES (Makefile:118 rejects any .apk
    # destination), so they are installed by BUILD_PREBUILT modules instead. The module keeps the
    # stock name so the artifact-path rule permits it: build/make/core/artifact_path_requirements.mk:9
    # allows `%__auto_generated_rro_vendor.apk` for STATIC_LIBRARIES, which is exactly how AOSP
    # installs its own generated vendor RROs. scripts/prebuilt_vendor.sh mirrors the APK(s) into
    # <device-dir>/prebuilt_apps/ before running this generator, and deploy_device.sh copies the
    # whole device folder into the build tree, so LOCAL_SRC_FILES resolve there.
    if apks:
        appdir = os.path.join(args.device_dir, "prebuilt_apps")
        os.makedirs(appdir, exist_ok=True)
        mk = os.path.join(appdir, "Android.mk")
        with open(mk, "w") as f:
            f.write("# GENERATED by tools/gen_vendor_staging.py from the staged Android 11 vendor\n"
                    "# tree. Do not edit by hand; regenerate.\n"
                    "#\n"
                    "# PRODUCT_COPY_FILES refuses .apk destinations (build/make/core/Makefile:118),\n"
                    "# so the stock vendor resource-overlay package is installed as BUILD_PREBUILT:\n"
                    "# module class STATIC_LIBRARIES + suffix .apk is what AOSP itself uses for\n"
                    "# generated RROs, and artifact_path_requirements.mk:9 allows that name pattern.\n"
                    "# The blob is copied unchanged, so /vendor/overlay keeps the stock RRO.\n\n")
            f.write("LOCAL_PATH := $(call my-dir)\n")
            for rel in apks:
                name = os.path.basename(rel)[:-4]
                subdir = os.path.dirname(rel) or "."
                src = os.path.join(appdir, rel)
                if not os.path.isfile(src):
                    print("  ! %s not staged in %s (run scripts/prebuilt_vendor.sh)" % (rel, appdir))
                f.write("\ninclude $(CLEAR_VARS)\n")
                f.write("LOCAL_MODULE := %s\n" % name)
                f.write("LOCAL_MODULE_CLASS := STATIC_LIBRARIES\n")
                f.write("LOCAL_MODULE_SUFFIX := .apk\n")
                f.write("LOCAL_SRC_FILES := %s\n" % rel)
                f.write("LOCAL_MODULE_PATH := $(TARGET_COPY_OUT_VENDOR)/%s\n" % subdir)
                f.write("include $(BUILD_PREBUILT)\n")
        with open(staging, "a") as f:
            f.write("\n# The vendor APKs above are installed by their modules, not by\n"
                    "# PRODUCT_COPY_FILES; the modules live in prebuilt_apps/Android.mk.\n")
            f.write("PRODUCT_PACKAGES += %s\n" % " ".join(os.path.basename(p)[:-4] for p in apks))
        print("wrote %s (%d prebuilt vendor apk module(s))" % (mk, len(apks)))
    print("wrote %s (%d copy entries, manifest=%s)" % (staging, len(entries), bool(manifest)))

    # Stock vendor properties -> PRODUCT_PROPERTY_OVERRIDES.
    props = []
    bp = args.build_prop or os.path.join(tree, "build.prop")
    if not os.path.exists(bp):
        print("  ! no stock vendor build.prop found at %s - vendor_props.mk will be empty" % bp)
    else:
        for line in open(bp, encoding="utf-8", errors="replace"):
            m = PROP_PROP_RE.match(line.strip())
            if not m:
                continue
            key, value = m.group(1), m.group(2)
            if key.startswith(PROP_SKIP_PREFIXES) or key in extra_skip or not value:
                continue
            if any(c in value for c in "&;$`\\"):
                continue
            props.append("%s=%s" % (key, value))
    props = sorted(set(props))
    out = os.path.join(args.device_dir, "vendor_props.mk")
    with open(out, "w") as f:
        f.write("# GENERATED by tools/gen_vendor_staging.py from the stock vendor build.prop.\n"
                "# Android 14 generates its own vendor build.prop, so the properties the Rockchip\n"
                "# HALs and the HCT apps read have to be declared here instead.\n"
                "# Keys the build assigns itself (or that collide) are dropped; if post_process_props\n"
                "# reports a duplicate, add it to vendor_props_skip.txt and regenerate.\n")
        if props:
            f.write("\nPRODUCT_PROPERTY_OVERRIDES += \\\n")
            f.write("    " + " \\\n    ".join(props) + "\n")
    print("wrote %s (%d properties)" % (out, len(props)))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
